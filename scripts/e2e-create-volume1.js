const http = require('http');
const PROJECT_ID = 'ce877373-da85-4e09-bb30-e7a41a930d1e';

function apiCall(method, path, body) {
    return new Promise((resolve, reject) => {
        const data = body ? JSON.stringify(body) : '';
        const options = {
            hostname: 'localhost', port: 3001, path, method,
            headers: { 'Content-Type': 'application/json' }
        };
        if (data) options.headers['Content-Length'] = Buffer.byteLength(data);
        const req = http.request(options, (res) => {
            let responseBody = '';
            res.on('data', chunk => responseBody += chunk);
            res.on('end', () => {
                try { resolve({ status: res.statusCode, data: JSON.parse(responseBody) }); }
                catch (_) { resolve({ status: res.statusCode, data: responseBody }); }
            });
        });
        req.on('error', reject);
        if (data) req.write(data);
        req.end();
    });
}

async function createMaterial(type, name, content, extra = {}) {
    const body = { projectId: PROJECT_ID, type, name, initialContent: content, currentContent: content, ...extra };
    const result = await apiCall('POST', '/api/materials', body);
    if (result.status === 201 || result.status === 200) {
        console.log(`  ✓ ${type}: ${name}`);
        return result.data;
    } else {
        console.error(`  ✗ ${type}: ${name} - ${result.status}`, typeof result.data === 'string' ? result.data.substring(0,100) : JSON.stringify(result.data).substring(0,100));
        return null;
    }
}

async function createChapter(chapterNumber, title, outline) {
    const body = { projectId: PROJECT_ID, chapterNumber, title, outline, status: 'outlined' };
    const result = await apiCall('POST', '/api/chapters', body);
    if (result.status === 201 || result.status === 200) {
        console.log(`  ✓ Ch${chapterNumber}: ${title}`);
        return result.data;
    } else {
        console.error(`  ✗ Ch${chapterNumber}: ${title} - ${result.status}`);
        return null;
    }
}

