async function deleteAutoGeneratedQuests(projectId) {
    const quests = await store.queryItems('quests', { projectId });
    let deleted = 0;
    for (const q of quests) {
        if (q.tags && q.tags.includes('auto-generated')) {
            await store.deleteItem('quests', q.id);
            deleted++;
        }
    }
    return deleted;
}

async function createLongTermQuests(projectId) {
    const now = new Date().toISOString();
    let created = 0;
    for (const quest of LONG_TERM_QUESTS) {
        const qId = uuidv4();
        const subQuestIds = [];
        for (const sub of quest.subQuests) {
            const subId = uuidv4();
            subQuestIds.push(subId);
            await store.setItem('quests', subId, {
                id: subId, projectId, parentId: qId,
                title: sub.title, description: sub.description,
                status: 'planned', priority: 'normal',
                sortOrder: created, materialIds: [], chapterIds: [],
                timelineEventIds: [], progress: 0, notes: '',
                tags: ['long-term-sub'], createdAt: now, updatedAt: now
            });
        }
        await store.setItem('quests', qId, {
            id: qId, projectId, parentId: null,
            title: quest.title, description: quest.description,
            status: 'planned', priority: quest.priority,
            sortOrder: created, materialIds: [], chapterIds: [],
            timelineEventIds: [], progress: 0, notes: '',
            tags: ['long-term-main'], subQuestIds,
            createdAt: now, updatedAt: now
        });
        created++;
        console.log(`  ✅ [${quest.priority}] ${quest.title} (${quest.subQuests.length}个子任务)`);
    }
    return created;
}

async function fixTimelineEvents(projectId) {
    const events = await store.queryItems('timeline-events', { projectId });
    let fixed = 0;
    for (const ev of events) {
        if (!ev.title || !ev.importance) {
            const updated = {
                ...ev,
                title: ev.title || ev.data?.title || ev.description?.substring(0, 30) || '未命名事件',
                importance: ev.importance || (ev.data?.isKeyEvent ? 'critical' : (ev.significance === 'critical' ? 'critical' : (ev.significance === 'major' ? 'high' : 'normal')))
            };
            await store.setItem('timeline-events', ev.id, updated);
            fixed++;
        }
    }
    return { total: events.length, fixed };
}

