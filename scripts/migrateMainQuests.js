    console.log('=== 主线任务数据迁移 ===');
    console.log(`项目ID: ${PID}\n`);

    // 1. 删除auto-generated的"第X章"quest
    const deleted = await deleteAutoGeneratedQuests(PID);
    console.log(`删除auto-generated quest: ${deleted}条\n`);

    // 2. 创建长期主线任务
    console.log('创建长期主线任务:');
    const created = await createLongTermQuests(PID);
    console.log(`\n创建长期主线: ${created}条\n`);

    // 3. 修复timeline-events字段
    const tlResult = await fixTimelineEvents(PID);
    console.log(`修复timeline-events: ${tlResult.fixed}/${tlResult.total}条补全title和importance\n`);

    // 验证结果
    const finalQuests = await store.queryItems('quests', { projectId: PID });
    const rootQuests = finalQuests.filter(q => !q.parentId);
    const subQuests = finalQuests.filter(q => q.parentId);
    console.log('=== 迁移结果 ===');
    console.log(`quests总数: ${finalQuests.length} (根任务: ${rootQuests.length}, 子任务: ${subQuests.length})`);
