/**
 * povRuleSectionBuilder.js — 视角规则约束区统一构建器
 *
 * 解决问题：
 *  - writer/reviser/firstReview/secondReview/fastReview 各自内联构建povRuleSection
 *  - 审核员缺少"判定标准"导致LLM误判主观推断为上帝视角
 *  - 判定标准散落多处，维护困难
 *
 * 统一方案（遵循"禁止黑名单、靠原则不靠枚举、统一入口"）：
 *  - 判定标准只在此文件定义一次
 *  - writer/reviser 使用 buildWriterPovRuleSection（创作约束口吻）
 *  - 审核员使用 buildReviewerPovRuleSection（审核依据口吻）
 *  - 判定靠二分法原则（主语是谁 + 作者断言/主角推测），禁止违规词黑名单
 */

/**
 * 视角违规判定标准（统一定义，所有agent共用）
 * 核心原则：靠二分法判定，不靠违规词黑名单
 *  - 第一步：主语是谁？主角→合规；NPC→进入第二步
 *  - 第二步：作者断言还是主角推测？断言→违规；推测→合规
 */
const POV_JUDGMENT_CRITERIA = `【视角违规判定标准 - 严格区分以下两类，误判即审核失误】
【真正违规-上帝视角】以下写法必须禁止/判❌：
1. 直接陈述他人内心想法（如"他心中暗想""她内心挣扎着要不要开口"——这里的"他/她"必须是NPC，不是主角）
2. 全知旁白描述主角不可能感知的信息（如"远处的某人正在密谋..."）
3. 数值化内心独白（如"胜算三成""成功率0%"）
4. 切换到他人视角描写其心理活动（如"此时，在另一边，张三正想着..."）
5. 作者直接陈述NPC心理状态（如"赵四将信将疑""李明心中一凛"——这是上帝视角，必须改为"赵四摸着下巴，眼神游移"等主角可观察的外部动作）
6. 作者直接断言NPC的认知/判断（如"完全忽略了风险""完全没意识到危险"——主角无法知道NPC内心是否"忽略"了风险，只能写"他对风险只字不提"或"似乎没把风险当回事"）
7. 作者总结多人的内心关系（如"三人互相嫌弃""他们的利益空前一致"——主角无法知道其他人是否"嫌弃"他，只能通过观察推测"看来这帮人虽然互相看不顺眼，但在这件事上达成了默契"）
8. 用"在他们眼里/在他们看来"等表述直接陈述NPC视角（如"在他们眼里，两个疯子的威胁性还不如一条野狗"——这是上帝视角，必须改为"看来这帮人把两个疯子当成了低威胁目标"等主角推测）
9. 直接陈述NPC的情绪定性（如"既没惊讶也没厌恶"——主角只能观察到"神色平静"，不能直接断定"没惊讶也没厌恶"，必须改为"脸上看不出喜怒"或"平静得让人心里发毛"）
【合规写法-主观推断】以下写法是写作标准技法，不得判违规/不得要求修改：
1. 主角通过观察他人表情/动作/语气推断其心理（如"他眼神一闪，似乎在算计什么"）
2. 主角的主观感受和比喻（如"那眼神看得我心里发毛，活像在看一块五花肉"）
3. 主角基于经验的猜测（如"看这架势，八成是来者不善"）
4. 战斗场景中主角通过对手动作判断其意图（如"他这一拳来势汹汹，分明是要置我于死地"）
5. 主角自己的内心独白和吐槽（如"林渊心中暗笑：这老东西被忽悠住了"——这是主角自己的心理，不是他人心理，合规）
6. 主角自己的回忆和联想（如"这股味道让他想起小时候母亲晒过的被子"——这是主角自己的回忆，不是NPC的心理，合规）
7. 主角自己的生理感受（如"他感到一阵恶心""胃里翻江倒海"——这是主角自己的感受，合规）
8. 主角推测NPC心理状态（如"这老家伙果然心虚""他八成是害怕了""分明是心虚"——这是主角基于观察的主观推测，不是作者全知陈述，合规）
9. 主角观察他人眼神/表情/动作的变化（如"眼神变得深邃而警惕""表情变得严肃""眉头一皱"——这些是主角可以观察到的外部表现，合规。"警惕""严肃"在这里是形容外部表现，不是内心状态）
10. 主角通过观察推测NPC的认知状态（如"看来他没把我的话当回事""似乎没意识到危险""八成是没听懂"——这是主角基于观察的推测，不是作者全知断言，合规）
【判定原则 - 判定前必须逐条确认】
- 第一步：确认"心中暗道/暗笑/暗想/心中"前面的主语是谁？如果是主角（如"林渊心中暗道"），则无论后面跟什么内容（包括对NPC心理的推测），都是主角的内心独白，合规
- 第二步：只有当"心中暗想/心中一凛"前面的主语是NPC（如"赵执事心中一凛"），且作者以全知视角直接陈述时，才是违规
- 第三步："主角推测NPC心理状态"（如"这老家伙果然心虚"）是主角的主观推断，不是上帝视角，合规
- 第四步："主角自己的内心独白/回忆/感受"是合规的第一人称/限知视角写法
- 第五步：区分"外部表现"和"内心状态"。眼神/表情/动作的变化是外部表现，主角可以观察，合规；只有直接陈述NPC内心感受（如"心中警惕""感到害怕"）才是上帝视角
- 第六步：区分"主角推测"和"作者断言"。"看来他没把风险当回事"是主角推测（合规）；"他完全忽略了风险"是作者断言（违规）。关键看用的是"看来/似乎/八成"等推测词，还是"完全/根本/丝毫"等断言词
- 第七步：区分"主角观察总结"和"作者全知总结"。"看着两人收起东西，林渊知道买卖成了"是主角观察总结（合规）；"三人互相嫌弃，利益空前一致"是作者全知总结（违规）
- 误把主角自己的心理/回忆/感受判为违规，属于严重审核失误
- 误把主角对NPC的主观推测判为上帝视角，属于严重审核失误
- 误把主角可观察的外部表现（如"眼神变得警惕"）判为上帝视角，属于严重审核失误
- 误把合规写法判为违规，属于审核失误
【典型误判示例 - 审核员必须避免】
- 误判："林渊心中暗道：赌对了，这老家伙果然心虚" → 这是主角的内心独白+主观推测，合规！不得判违规
- 误判："林渊心中暗笑：这老东西被忽悠住了" → 这是主角的内心独白，合规！不得判违规
- 误判："他拍了拍身上的土，眼神变得深邃而警惕" → "眼神变得警惕"是主角可观察的外部表现，合规！不得判违规
- 正确判违规："赵执事心中一凛" → 这是NPC的心理，作者直接陈述，违规
- 正确判违规："此时，在另一边，张三正想着" → 切换到他人视角，违规
- 正确判违规："声音轻得只有自己能听见" → 主角无法感知"只有自己能听见"，违规
- 正确判违规："他完全忽略了风险" → 作者断言NPC内心，违规
- 正确判违规："三人互相嫌弃，利益空前一致" → 作者全知总结多人内心，违规
- 正确判违规："在他们眼里，两个疯子不如一条野狗" → 作者直接陈述NPC视角，违规
- 正确判违规："既没惊讶也没厌恶" → 作者直接陈述NPC情绪定性，违规`;

/**
 * 构建writer/reviser的视角规则约束区
 * @param {object} styleProfile - 项目styleProfile
 * @returns {string} 视角铁律约束区（含判定标准）
 */
function buildWriterPovRuleSection(styleProfile) {
    const povRule = styleProfile?.povRule;
    if (!povRule) return '';
    return `\n\n【⚠️ 视角铁律 - 必须严格遵守，违反即退回重写】\n${povRule}\n${POV_JUDGMENT_CRITERIA}`;
}

/**
 * 构建审核员的视角规则约束区
 * @param {object} project - 项目对象（含styleProfile）
 * @returns {string} 视角规则审核依据区（含判定标准）
 */
function buildReviewerPovRuleSection(project) {
    const povRule = project?.styleProfile?.povRule;
    if (!povRule) return '';
    return `\n\n【视角规则（审核依据——以此为准，不得自行提高标准）】\n${povRule}\n注意：视角违规的判定必须以此规则为准。如果此规则允许双视角/视角切换，则不得判定视角切换为违规。只有当正文违反了此规则中的明确禁止项时，才能判定视角违规。\n${POV_JUDGMENT_CRITERIA}`;
}

module.exports = {
    buildWriterPovRuleSection,
    buildReviewerPovRuleSection,
    POV_JUDGMENT_CRITERIA
};
