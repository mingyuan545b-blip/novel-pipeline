'use strict';

/**
 * craftQualitySpec — 人物工艺质量标准（高光 / 名言 / 人格魅力）
 *
 * 目的：把"什么是高光、什么是名言、什么是魅力"变成**可判定**的定义 + 正反例 + 禁词表，
 *       供「编年史提取 prompt」「人物工艺设计器」「素材深度提示」共用（单一数据源）。
 * 依据：docs/design/角色编年史升级-多维分层与素材质检.md §十（2026-10-08）
 *
 * 实测反例来源（本仓库真实编年史）：
 *   - why 全部是评论腔："展现了…/体现了…/确立了…/立住了…"（15 条高光里 10 条命中）
 *   - quote 收进过场句："上车。""进去了。""几多钱？""莫搞。"
 *   - 高光 what 写成剧情摘要（"使用空白勘定笔…冻结探员行动权，趁乱带走流浪汉"）
 */

/** 评论腔：用"读后感/论文"语气冒充记忆点。出现在 why 里即不合格 */
const COMMENTARY_WORDS = Object.freeze([
    '展现了', '体现出', '体现', '凸显', '彰显', '标志着', '生动', '侧面', '营造', '渲染',
    '立住', '立住了', '暗示', '推动剧情', '铺垫', '刻画', '强化', '确立了', '衬托',
]);

/** 过场句 / 功能句（指令·应答·招呼·纯问价）——不是名言 */
const FILLER_LINE = /^(进去了?|上车|下车|走吧|走着|好的|好吧|行|嗯|哦|是|对|来了|知道了|几多钱|多少钱|莫搞|没事|不知道|别回头|不管是什么|小心|快点|闭嘴|多谢)[。！？…，,、\s]*$/;

/** 高光四问：全过才算高光（去名测试 / 代价测试 / 画面测试 / 不可逆测试） */
const HIGHLIGHT_TESTS = Object.freeze([
    { id: 'screenshot', name: '可截图', desc: '一句话能画出画面：谁、在什么处境、做了什么动作或说了哪句话（必须含动作或台词原文）' },
    { id: 'only-him', name: '只有他会做', desc: '把他的名字换成别人，这个选择就不成立或不好看（去名测试）' },
    { id: 'cost', name: '有代价/反差', desc: '他为此失去了/放弃了/背负了什么；赢要付代价，输要有姿态' },
    { id: 'irreversible', name: '不可逆', desc: '此后他的立场/关系/命运变了（与"事迹"的区别：事迹=做了什么，高光=哪一刻他成了他）' },
]);

/** 名言三问：全过才算名言 */
const QUOTE_TESTS = Object.freeze([
    { id: 'standalone', name: '去语境测试', desc: '单独贴出来还能站得住、能被引用（"上车。""进去了。"这类过场句不算）' },
    { id: 'inferable', name: '反推测试', desc: '不看名字也能从这句推出说话人的身份/处境/脾气' },
    { id: 'weight', name: '重量测试', desc: '它承载了他的信念、恐惧、谎言或命运抉择（纯信息交代不算）' },
]);

/** 人格魅力：不是形容词，是压力下的选择函数 */
const CHARISMA_FORM = '当【处境】时，他宁可【做X】，也不【做Y】——且 X 要付代价';

/** 现代网络梗：只准在题材内行话里造梗，禁止把现实网络语塞进正文/名言/口头禅 */
const MODERN_MEME_WORDS = Object.freeze([
    'yyds', '绝绝子', '内卷', '躺平', 'emo', 'KPI', 'OKR', '打工人', '社畜', '破防',
    '栓Q', '蚌埠住了', 'awsl', '爷青回', '我可以', '笑死', '麻了', '整挺好', '真的会谢',
    '666', '点赞', '差评', '开挂', '氪金', '进度条', '用户体验', '可持续发展', '客服',
]);

/** 口头禅/名梗三问：可复用 / 有辨识度 / 只属于他 */
const CATCHPHRASE_TESTS = Object.freeze([
    { id: 'repeatable', name: '可复用', desc: '它是能反复出现的口头习惯或招牌话，不是一次性对白' },
    { id: 'recognizable', name: '有辨识度', desc: '单独拎出来就知道是谁说的（别人说会很怪）' },
    { id: 'in-world', name: '长在题材里', desc: '用世界观内行话造梗，禁现代网络梗（yyds/内卷/KPI/破防）' },
]);

function hasModernMeme(text) {
    const s = String(text == null ? '' : text).toLowerCase();
    return MODERN_MEME_WORDS.some((w) => s.includes(w.toLowerCase()));
}

function hasCommentaryVoice(text) {
    const s = String(text == null ? '' : text);
    return COMMENTARY_WORDS.some((w) => s.includes(w));
}

function isFillerLine(text) {
    return FILLER_LINE.test(String(text == null ? '' : text).trim());
}

/** 编年史提取 / 人物设计共用的工艺指导块（塞进 prompt） */
function buildCraftGuidance() {
    return `【工艺标准：什么是高光 / 名言 / 魅力——不合标准一律不写】

一、高光时刻（名场面）＝角色"成了他自己"的那一个瞬间，不是"他做了什么"的概述。
四条全过才算（缺一不收）：
1. 可截图：一句话能画出画面——谁、在什么处境、做了什么动作或说了哪句话（必须含动作或台词原文）。
2. 只有他会做：把名字抹掉换成别人，这个选择就不成立或不好看。
3. 有代价/反差：他失去了/放弃了/背负了什么（赢要付代价，输要有姿态）。
4. 不可逆：此后他的立场/关系/命运变了。
正例：《英雄联盟》卡蜜尔"我曾踏足山巅，也曾坠入低谷，二者都让我受益匪浅"——处境=回望一生，
     她把"跌入低谷"重估成收获，一句话定住她的冷傲与阶级观（有代价、不可逆）。
反例① 剧情摘要（×）："使用空白勘定笔在桌面划出蓝光弧线，制造临时规则屏障冻结探员行动权，趁乱带走流浪汉。"
反例② 评论腔（×）："展现了其核心能力的高光时刻，体现了绝境中的冷静与战术智慧。"（这是读后感，不是名场面）

二、名言/金句＝能被单独引用、且只属于这个人的那句话。
三问全过才算（缺一不收）：
1. 去语境测试：单独贴出来还站得住（"上车。""进去了。""几多钱？"这类指令/应答/过场句不算）。
2. 反推测试：不看名字也能推出说话人的身份/处境/脾气。
3. 重量测试：它承载了他的信念、恐惧、谎言或命运抉择。
正例：《凡人修仙传》何仙师留给韩立的"人生如棋，落子无悔"——临终赠言压在主角远走乱星海的命运节点上，
     台词不是因为漂亮才被记住，而是因为挂在一段不可回头的人生上。
反例（×）："上车。" / "进去了。" / 一句只用来交代信息的对白。

三、人格魅力＝压力下的选择模式，不是形容词。
写法固定为：${CHARISMA_FORM}。
反例（×）："智勇双全、游走于灰色地带"（形容词堆砌，无法执行）。

四、口头禅/名梗＝能反复出现、且只属于他的招牌话（不是一次性对白，也不是网络梗）。
三问全过才算：${CATCHPHRASE_TESTS.map((t) => `${t.name}=${t.desc}`).join('；')}。
正例："这账，平了才叫结"（记账人的世界观内行话，别人说会怪）。
反例（×）："上车。"（过场句）、"yyds/内卷/KPI"（现代网络梗乱入古风）。

四、输出前逐条自检（三步）
① 把这条的角色名抹掉，句子还成立吗？成立→删。
② why 里有没有评论词（展现/体现/凸显/彰显/标志着/生动/侧面/营造/渲染/暗示/铺垫/推动剧情/刻画）？有→改写成因果句。
③ 这条能不能被任何一本同类书照抄？能→删。
宁缺毋滥：没有就返回空数组，绝不用剧情摘要或读后感凑数。`;
}

